# ==============================================================================
# ASTRAL SPECIES TREE PLOTTING
# ==============================================================================
# Load required libraries
library(ggtree)
library(treeio)
library(ape)
library(ggplot2)

# ==========================================
# 1. USER CONTROLS & I/O
# ==========================================
setwd("/path/to/working/directory")

INPUT_TREE <- "ASTRAL_SpeciesTree_purged.tre"
OUTPUT_IMAGE <- "ASTRAL_Publication_Tree.png"
OUTGROUP_ID <- "basvit_genome"

# Dictionary mapping raw tip IDs to final publication-ready names
TAXA_MAP <- c(
  "Laemanctus_serratus" = "L.serratus_zoo",
  "Laemanctus_longipes" = "L.longipes_zoo",
  "C01" = "Laemanctus_UNAH.1",
  "C02" = "Laemanctus_UNAH.2",
  "C03" = "Laemanctus_UNAH.3",
  "C04" = "Laemanctus_Suyapa.1",
  "C05" = "Laemanctus_Suyapa.2",
  "C06" = "Laemanctus_Suyapa.3",
  "F01" = "Laemanctus_Zoo.1",
  "F03" = "Laemanctus_Zoo.3",
  "Basiliscus_vittatus" = "B.vittatus_GCA_046270045.1",
  "Laemanctus_Mexico" = "L.serratus_GCA_041295975.1"
)

# ==============================================================================
# 2. READ, ROOT, AND TRANSLATE TAXA
# ==============================================================================
my_tree <- read.tree(INPUT_TREE)
rooted_tree <- root(my_tree, outgroup = OUTGROUP_ID, resolve.root = TRUE)

# Apply taxonomic translation dynamically
for (raw_name in names(TAXA_MAP)) {
  rooted_tree$tip.label <- gsub(raw_name, TAXA_MAP[[raw_name]], rooted_tree$tip.label)
}

# The outgroup name may have changed during translation, update the target
FINAL_OUTGROUP <- TAXA_MAP[[OUTGROUP_ID]]
if(is.null(FINAL_OUTGROUP)) FINAL_OUTGROUP <- OUTGROUP_ID

# ==============================================================================
# 3. ASTRAL-SPECIFIC BRANCH HANDLING & SHRINKING
# ==============================================================================
# ASTRAL does not estimate terminal branch lengths. R reads them as NA.
# We assign an arbitrary visual length of 1.0 coalescent unit to draw the tips cleanly.
if(any(is.na(rooted_tree$edge.length))) {
  rooted_tree$edge.length[is.na(rooted_tree$edge.length)] <- 1.0
}

root_node <- Ntip(rooted_tree) + 1
basal_edges <- which(rooted_tree$edge[,1] == root_node)
basal_children <- rooted_tree$edge[basal_edges, 2] 

outgroup_idx <- which(rooted_tree$tip.label == FINAL_OUTGROUP)
outgroup_edge <- which(rooted_tree$edge[,2] == outgroup_idx)

# Shrink BOTH basal branches to slide the tree left
rooted_tree$edge.length[basal_edges] <- 0.1 

# Nodes to hide (ONLY applied to the internal coalescent branch lengths)
nodes_to_hide_ml <- c(basal_children, outgroup_idx)

# ==============================================================================
# 4. DATA PREPARATION (LPP & Coalescent Units)
# ==============================================================================
p <- ggtree(rooted_tree, branch.length="branch.length")

# A) Pre-calculate ASTRAL LPP Support Values
p$data$bs_text <- ""
p$data$bs_text[!p$data$isTip] <- rooted_tree$node.label
p$data$bs_text[p$data$node == root_node | is.na(p$data$bs_text)] <- ""

# Scrub out any literal "Root" string artifacts generated by ape::root()
p$data$bs_text[p$data$bs_text == "Root"] <- ""

# B) Pre-calculate Coalescent Branch Lengths (Hiding arbitrary terminal 1.0s)
p$data$ml_text <- ""
valid_ml <- !is.na(p$data$branch.length) & !p$data$isTip & !(p$data$node %in% nodes_to_hide_ml)
p$data$ml_text[valid_ml] <- round(p$data$branch.length[valid_ml], 3)

# ==============================================================================
# 5. PLOT AND SAVE
# ==============================================================================
suppressWarnings({
  p <- p + 
    geom_tiplab(size=3.5, offset=0.05, fontface="italic") + 
    # LPP Support (Blue)
    geom_text(aes(x = x, y = y, label = bs_text), color="blue", size=3, vjust=1.2, hjust=1.2) +
    # Internal Coalescent Units (Darkred)
    geom_text(aes(x = branch, y = y, label = ml_text), color="darkred", size=2.5, vjust=-0.5) + 
    # Slash Mark for the Outgroup
    geom_text2(aes(subset = (node == outgroup_idx), x = branch), label = "//", size = 5, vjust = 0.3, color = "black", fontface = "bold") +
    # Note indicating terminal lengths are NA in ASTRAL
    geom_text2(aes(subset = (node == outgroup_idx), x = branch), label = "N/A", size = 2.5, vjust = -1.5, color = "darkred") +
    theme_tree2() +
    hexpand(0.4) +
    theme(plot.title = element_blank(), plot.subtitle = element_blank())
  
  ggsave(OUTPUT_IMAGE, plot = p, width = 10, height = 10, units = "in", dpi=300)
})
